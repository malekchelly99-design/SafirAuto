from rest_framework import serializers


class VehicleSerializer(serializers.Serializer):
    """Serializer for vehicle dicts from repository."""
    id = serializers.CharField(read_only=True)
    reference = serializers.CharField(read_only=True)
    status = serializers.ChoiceField(
        choices=['BROUILLON', 'PUBLIÉ', 'RÉSERVÉ', 'VENDU', 'ARCHIVÉ'],
        default='BROUILLON'
    )
    brand = serializers.CharField(max_length=100)
    model = serializers.CharField(max_length=100)
    version = serializers.CharField(max_length=200, required=False, allow_blank=True)
    year = serializers.IntegerField()
    condition = serializers.ChoiceField(
        choices=['Neuf', 'Occasion', 'Collection', 'Démonstration']
    )
    price = serializers.FloatField()
    old_price = serializers.FloatField(required=False, allow_null=True)
    currency = serializers.CharField(default='EUR')
    mileage = serializers.IntegerField()
    fuel_type = serializers.CharField(max_length=50)
    transmission = serializers.CharField(max_length=50)
    body_type = serializers.CharField(max_length=50)
    horsepower = serializers.IntegerField(required=False, allow_null=True)
    engine_size = serializers.FloatField(required=False, allow_null=True)
    cylinders = serializers.IntegerField(required=False, allow_null=True)
    doors = serializers.IntegerField(required=False, allow_null=True)
    seats = serializers.IntegerField(required=False, allow_null=True)
    owners_count = serializers.IntegerField(required=False, allow_null=True)
    first_registration = serializers.CharField(max_length=20, required=False, allow_blank=True)
    country_origin = serializers.CharField(max_length=100, required=False, allow_blank=True)
    exterior_color = serializers.CharField(max_length=100, required=False, allow_blank=True)
    interior_color = serializers.CharField(max_length=100, required=False, allow_blank=True)
    upholstery = serializers.CharField(max_length=100, required=False, allow_blank=True)
    warranty = serializers.BooleanField(required=False, default=False)
    warranty_months = serializers.IntegerField(required=False, allow_null=True)
    service_history = serializers.BooleanField(required=False, default=False)
    accident_history = serializers.BooleanField(required=False, default=False)
    imported = serializers.BooleanField(required=False, default=False)
    title = serializers.CharField(max_length=300, required=False, allow_blank=True)
    short_description = serializers.CharField(required=False, allow_blank=True)
    description = serializers.CharField(required=False, allow_blank=True)
    featured = serializers.BooleanField(required=False, default=False)
    badge = serializers.CharField(max_length=50, required=False, allow_blank=True)
    primary_image = serializers.CharField(max_length=500, required=False, allow_blank=True)
    images = serializers.ListField(child=serializers.CharField(), required=False, default=list)
    equipment = serializers.ListField(child=serializers.CharField(), required=False, default=list)
    created_at = serializers.CharField(read_only=True)
    updated_at = serializers.CharField(read_only=True)


class VehicleListSerializer(serializers.Serializer):
    """Lightweight serializer for listing pages."""
    id = serializers.CharField()
    reference = serializers.CharField()
    status = serializers.CharField()
    brand = serializers.CharField()
    model = serializers.CharField()
    version = serializers.CharField(allow_blank=True, allow_null=True)
    year = serializers.IntegerField()
    condition = serializers.CharField()
    price = serializers.FloatField()
    old_price = serializers.FloatField(allow_null=True)
    currency = serializers.CharField()
    mileage = serializers.IntegerField()
    fuel_type = serializers.CharField()
    transmission = serializers.CharField()
    body_type = serializers.CharField()
    horsepower = serializers.IntegerField(allow_null=True)
    exterior_color = serializers.CharField(allow_blank=True, allow_null=True)
    owners_count = serializers.IntegerField(allow_null=True)
    title = serializers.CharField(allow_blank=True, allow_null=True)
    short_description = serializers.CharField(allow_blank=True, allow_null=True)
    featured = serializers.BooleanField()
    badge = serializers.CharField(allow_blank=True, allow_null=True)
    primary_image = serializers.CharField(allow_blank=True, allow_null=True)
    images = serializers.ListField(child=serializers.CharField())
    created_at = serializers.CharField()
